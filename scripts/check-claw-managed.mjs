import assert from 'node:assert/strict';
import { buildConfig, channelReady, publicStatus, acceptRequest,probeMcp } from '../src-tauri/resources/claw-core.mjs';
const input = { baseUrl:'https://example.invalid/v1', model:'demo', apiKey:'secret-key', mcp:{mcp:{servers:{xmission:{url:'http://127.0.0.1:43858/mcp',headers:{Authorization:'Bearer private'}}}}} };
const config=buildConfig(input,{channels:{qqbot:{accounts:{old:{appId:'1'}}}},custom:'preserve'},'token','C:/owned/work',19442);
assert.equal(config.models.providers.xmission.apiKey,'${XMISSION_MODEL_KEY}');
assert.equal(config.channels.qqbot.accounts.old.appId,'1');
assert.equal(config.custom,'preserve');
assert.equal(config.gateway.bind,'loopback');
assert.ok(config.mcp.servers.xmission);
assert.equal(config.mcp.servers.xmission.headers.Authorization,'Bearer ${XMISSION_MCP_TOKEN}');
assert.ok(config.plugins.allow.includes('openclaw-qqbot'));
assert.ok(!JSON.stringify(config).includes('secret-key'));
const responses=buildConfig({...input,baseUrl:'https://example.invalid/v1/responses'}, {},'token','C:/owned/work',19442);
assert.equal(responses.models.providers.xmission.api,'openai-responses');
assert.equal(responses.models.providers.xmission.baseUrl,'https://example.invalid/v1');
assert.equal(channelReady({channelAccounts:{qqbot:[{configured:true,running:true,connected:false}]}}),false);
assert.equal(channelReady({channelAccounts:{qqbot:[{configured:true,running:true,connected:true}]}}),true);
assert.equal(channelReady({channels:{qqbot:{running:true}}}),false);
assert.equal(acceptRequest({headers:{authorization:'Bearer secret',origin:'https://evil.invalid',host:'127.0.0.1:8888'}},'secret',8888),false);
assert.equal(acceptRequest({headers:{authorization:'Bearer wrong',host:'127.0.0.1:8888'}},'secret',8888),false);
assert.equal(acceptRequest({headers:{authorization:'Bearer secret',host:'127.0.0.1:8888'}},'secret',8888),true);
assert.ok(!JSON.stringify(publicStatus({phase:'ready',message:'ok',apiKey:'secret-key',credentials:input,mcpConnected:true})).includes('secret'));
assert.equal(publicStatus({phase:'preparing',progress:40}).progress,40,'progress reaches the native UI boundary');
assert.equal(publicStatus({phase:'idle',progress:NaN}).progress,null,'unknown progress stays indeterminate');
assert.equal(publicStatus({phase:'preparing',progress:101}).progress,100);
const requests=[];
const server=input.mcp.mcp.servers.xmission;
assert.equal(await probeMcp(server,async(url,options)=>{requests.push(JSON.parse(options.body).method);assert.equal(options.headers.Authorization,'Bearer private');return {ok:true,json:async()=>({result:requests.length===1?{protocolVersion:'2025-11-25',capabilities:{tools:{}}}:{tools:[{name:'xmission_list_tasks'}]}})};}),true);
assert.deepEqual(requests,['initialize','tools/list']);
assert.equal(await probeMcp(server,async()=>({ok:false,status:401})),false,'revoked token immediately clears reachability');
assert.equal(await probeMcp(server,async()=>{throw Error('disconnected');}),false);
assert.equal(await probeMcp(server,async()=>({ok:true,json:async()=>({error:{code:-32600}})})),false);
console.log('Managed config isolation, credentials, readiness and HTTP boundary passed.');
